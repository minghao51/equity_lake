#: The tracked anchor for the gitignored archive.
ROOT = Path(__file__).resolve().parents[3]
DEFAULT_ANCHOR = ROOT / "docs" / "finding" / "20261123-01-r02-recovery-receipt.md"

#: The six archived files, and the two digest bindings the anchor also records.
ARTIFACT_NAMES: tuple[str, ...] = ("baselines.json", "metrics.json", "predictions.parquet", "protocol.json", "report.md", "run.json")
BINDING_NAMES: tuple[str, ...] = ("prespecification_digest", "protocol_digest")

FOLD_NAMES: tuple[str, ...] = ("validation", "test")
ARM_NAMES: tuple[str, ...] = ("primary_model", "simple_model", "technical_rule", "no_skill")
ARM_LABELS: dict[str, str] = {
    "primary_model": "primary (gradient boosting)",
    "simple_model": "simple model (logistic regression)",
    "technical_rule": "technical rule (momentum-20)",
    "no_skill": "no skill (base rate)",
}
DISCRIMINATION_KEYS: tuple[str, ...] = ("rows", "brier_score", "roc_auc", "accuracy", "mean_probability", "base_rate")
ECONOMIC_KEYS: tuple[str, ...] = ("sessions", "net_return", "sharpe_ratio", "max_drawdown", "mean_daily_return", "mean_positions")

#: Recomputed and reported floats must agree to this absolute tolerance (most agree exactly).
TOLERANCE = 1e-9

_ANCHOR_ROW = re.compile(r"^\|\s*`(?P<name>[^`]+)`\s*\|\s*`(?P<digest>[0-9a-f]{64})`", re.MULTILINE)


class VerificationError(ValueError):
    """The archive could not be verified (unreadable anchor, unusable inputs)."""


class ArtifactsAbsent(FileNotFoundError):
    """There is no archive to verify; nothing is regenerated by refitting."""


@dataclass
class Outcome:
    """The verification result: what was checked, what failed, what stayed unverified."""

    research_dir: Path
    checked: int = 0
    mismatches: list[str] = field(default_factory=list)
    unverified: list[str] = field(default_factory=list)
    findings: list[str] = field(default_factory=list)
    digests: dict[str, str] = field(default_factory=dict)

    @property
    def verified(self) -> bool:
        """True when nothing mismatched."""
        return not self.mismatches


class _Ledger:
    """Accumulates checks, mismatches and the explicitly unverified remainder."""

    def __init__(self) -> None:
        self.outcome = Outcome(research_dir=Path())

    def expect(self, name: str, ok: bool, detail: str = "") -> None:
        self.outcome.checked += 1
        if not ok:
            self.outcome.mismatches.append(name if not detail else f"{name}: {detail}")

    def close(self, name: str, observed: float | None, reported: float | None, tolerance: float = TOLERANCE) -> None:
        self.outcome.checked += 1
        if observed is None or reported is None or not math.isclose(observed, reported, rel_tol=0.0, abs_tol=tolerance):
            self.outcome.mismatches.append(f"{name}: recomputed {observed!r} vs reported {reported!r}")

    def unverified_reason(self, reason: str) -> None:
        self.outcome.unverified.append(reason)

    def finding(self, text: str) -> None:
        self.outcome.findings.append(text)


def sha256_file(path: Path) -> str:
    """The sha256 of one archived file, read in chunks."""
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_anchor(anchor_path: Path) -> dict[str, str]:
    """Read the tracked digest table (``| `file` | `sha256` | … |`` rows) from the receipt."""
    try:
        text = Path(anchor_path).read_text(encoding="utf-8")
    except OSError as exc:
        raise VerificationError(f"the tracked digest anchor {anchor_path} is unreadable: {exc}") from exc
    entries = {match.group("name"): match.group("digest") for match in _ANCHOR_ROW.finditer(text)}
    if not entries:
        raise VerificationError(f"{anchor_path} carries no `| `file` | `sha256` |` rows; without an anchor nothing can be verified")
    return entries


def _load_json_artifacts(research_dir: Path, ledger: _Ledger) -> dict[str, dict[str, Any]]:
    payloads: dict[str, dict[str, Any]] = {}
    for name in ("baselines.json", "metrics.json", "protocol.json", "run.json"):
        path = research_dir / name
        if not path.is_file():
            continue
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            ledger.expect(f"{name} is readable JSON", False, str(exc))
            continue
        if isinstance(payload, dict):
            payloads[name] = payload
        else:
            ledger.expect(f"{name} is a JSON object", False, f"got {type(payload).__name__}")
    return payloads


def _load_predictions(research_dir: Path, ledger: _Ledger) -> pl.DataFrame | None:
    path = research_dir / "predictions.parquet"
    if not path.is_file():
        return None
    try:
        return pl.read_parquet(path)
    except Exception as exc:  # the parquet reader raises library-specific errors on a damaged file
        ledger.expect("predictions.parquet is readable", False, str(exc))
        return None


def _check_digests(research_dir: Path, anchor: Mapping[str, str], ledger: _Ledger) -> None:
    recorded = {name: digest for name, digest in anchor.items() if name not in BINDING_NAMES}
    present = {path.name for path in research_dir.iterdir() if path.is_file()}
    ledger.expect(
        "the anchor records exactly the six archived files",
        set(recorded) == set(ARTIFACT_NAMES) == present,
        f"anchor {sorted(recorded)} / expected {sorted(ARTIFACT_NAMES)} / present {sorted(present)}",
    )
    for name in sorted(set(recorded) | (present & set(ARTIFACT_NAMES))):
        path = research_dir / name
        if not path.is_file():
            ledger.expect(f"digest {name}", False, "recorded in the anchor but absent from the archive")
            continue
        observed = sha256_file(path)
        ledger.outcome.digests[name] = observed
        ledger.expect(f"digest {name}", observed == recorded.get(name), f"sha256 {observed} != anchored {recorded.get(name)}")


def _check_binding(
    research_dir: Path,
    anchor: Mapping[str, str],
    payloads: Mapping[str, Mapping[str, Any]],
    predictions: pl.DataFrame | None,
    ledger: _Ledger,
) -> None:
    expected_protocol = r02.r02_protocol().digest()
    expected_spec = r02.r02_spec().digest()
    for name, expected in (("protocol_digest", expected_protocol), ("prespecification_digest", expected_spec)):
        ledger.expect(
            f"anchor {name} is the digest the frozen code re-derives",
            anchor.get(name) == expected,
            f"anchored {anchor.get(name)} vs re-derived {expected}",
        )

    models: dict[str, Any] = {
        "protocol.json": r02.R02ProtocolArtifact,
        "metrics.json": r02.R02MetricsArtifact,
        "baselines.json": r02.R02BaselinesArtifact,
        "run.json": r02.R02RunManifest,
    }
    for name, payload in payloads.items():
        model = models.get(name)
        if model is not None:
            try:
                model.model_validate(payload)
                ledger.expect(f"{name} still satisfies its artifact contract", True)
            except Exception as exc:  # pydantic refuses a changed basis, disclosure or promotion
                ledger.expect(f"{name} still satisfies its artifact contract", False, str(exc).splitlines()[0])
        ledger.expect(f"{name} carries the frozen protocol digest", payload.get("protocol_digest") == expected_protocol)
        ledger.expect(f"{name} carries the frozen prespecification digest", payload.get("prespecification_digest") == expected_spec)
        ledger.expect(f"{name} keeps the one coverage basis", payload.get("coverage_basis") == r02.R02_BASIS == "vendor_events_no_clock")
        ledger.expect(f"{name} carries the fixed disclosure verbatim", payload.get("disclosure") == r02.R02_DISCLOSURE)
        ledger.expect(f"{name} promotes nothing", payload.get("promoted") is False)

    protocol_payload = payloads.get("protocol.json", {})
    ledger.expect(
        "protocol.json embeds the frozen protocol payload",
        protocol_payload.get("frozen_protocol") == r02.r02_protocol().protocol_payload(),
    )
    ledger.expect(
        "protocol.json embeds the frozen prespecification",
        protocol_payload.get("prespecification") == r02.r02_spec().model_dump(mode="json"),
    )
    run_payload = payloads.get("run.json", {})
    ledger.expect(
        "run.json binds the protocol identity",
        run_payload.get("protocol_binding") == {"protocol_digest": expected_protocol, "protocol_experiment": r02.r02_protocol().experiment},
    )
    if predictions is not None:
        for column, expected_values in (
            ("protocol_digest", {expected_protocol}),
            ("prespecification_digest", {expected_spec}),
            ("coverage_basis", {r02.R02_BASIS}),
            ("disclosure", {r02.R02_DISCLOSURE}),
        ):
            ledger.expect(f"every prediction row carries the same {column}", set(predictions[column].unique().to_list()) == expected_values)
    stamp = protocol_payload.get("manifest_name")
    if isinstance(stamp, str):
        _check_manifest(research_dir, stamp, expected_protocol, expected_spec, ledger)
    else:
        ledger.expect("protocol.json records the frozen manifest name", False, f"manifest_name {stamp!r}")


def _check_manifest(research_dir: Path, stamp: str, expected_protocol: str, expected_spec: str, ledger: _Ledger) -> None:
    protocols_dir = research_dir.parent / "protocols"
    path = protocols_dir / f"{stamp}-{expected_protocol[:12]}.manifest.json"
    if not protocols_dir.is_dir():
        ledger.unverified_reason(
            f"protocol<->manifest binding: {protocols_dir} is not next to the archive, so the R00 manifest cannot be re-read here"
        )
        return
    if not path.is_file():
        ledger.expect("the R00 manifest named by the archive is present", False, f"{path.name} is missing from {protocols_dir}")
        return
    raw = path.read_text(encoding="utf-8")
    try:
        record = FrozenProtocol.model_validate(json.loads(raw))
    except Exception as exc:  # a manifest that no longer self-binds refuses validation
        ledger.expect("the R00 manifest self-validates", False, str(exc).splitlines()[0])
        return
    ledger.expect("the R00 manifest is byte-identical to its canonical form", record.canonical_json() == raw)
    ledger.expect("the R00 manifest carries the frozen protocol digest", record.protocol_digest == expected_protocol)
    ledger.expect(
        "the R00 manifest binds the frozen prespecification digest",
        record.input_digests.get("r02_prespecification") == expected_spec,
        f"input_digests {record.input_digests}",
    )
    ledger.expect("the R00 manifest embeds the frozen protocol payload", record.protocol.protocol_payload() == r02.r02_protocol().protocol_payload())


def _fold_frame(predictions: pl.DataFrame, fold: str) -> pl.DataFrame:
    identity = ["market", "mic", "symbol"]
    return predictions.filter(pl.col("fold") == fold).sort(["date", *identity])


def _session_blocks(frame: pl.DataFrame, sessions: Sequence[date]) -> tuple[dict[date, int], dict[date, int]]:
    """Row offsets per session, exactly as ``run_r02`` lays them out for the bootstrap."""
    starts: dict[date, int] = {}
    counts: dict[date, int] = {}
    position = 0
    for session in sessions:
        size = frame.filter(pl.col("date") == session).height
        starts[session] = position
        counts[session] = size
        position += size
    return starts, counts


def _recompute_discrimination(predictions: pl.DataFrame, metrics: Mapping[str, Any], ledger: _Ledger) -> None:
    folds = metrics.get("folds", {})
    evidence = metrics.get("folds_evidence", {})
    for fold in FOLD_NAMES:
        frame = _fold_frame(predictions, fold)
        sessions = sorted(set(frame["date"].to_list()))
        reported = folds.get(fold, {})
        ledger.expect(f"folds/{fold}/rows", frame.height == reported.get("rows"), f"{frame.height} vs {reported.get('rows')}")
        ledger.expect(f"folds/{fold}/sessions", len(sessions) == reported.get("sessions"), f"{len(sessions)} vs {reported.get('sessions')}")
        fold_evidence = evidence.get(fold, {})
        ledger.expect(f"folds_evidence/{fold}/rows", frame.height == fold_evidence.get("rows"), f"{frame.height} vs {fold_evidence.get('rows')}")
        ledger.expect(
            f"folds_evidence/{fold}/decision_date_min",
            str(min(sessions)) == evidence.get(fold, {}).get("decision_date_min"),
            f"{min(sessions)} vs {evidence.get(fold, {}).get('decision_date_min')}",
        )
        ledger.expect(
            f"folds_evidence/{fold}/decision_date_max",
            str(max(sessions)) == evidence.get(fold, {}).get("decision_date_max"),
            f"{max(sessions)} vs {evidence.get(fold, {}).get('decision_date_max')}",
        )
        ledger.expect(
            f"folds_evidence/{fold}/label_end_date_max",
            str(frame["label_end_date"].max()) == evidence.get(fold, {}).get("label_end_date_max"),
        )

        labels = frame["outcome"].cast(pl.Float64).to_numpy()
        starts, counts = _session_blocks(frame, sessions)
        intervals = metrics.get("intervals", {}).get(fold, {})
        for arm in ARM_NAMES:
            probabilities = frame[f"probability_{arm}"].to_numpy()
            observed = r02._discrimination(labels, probabilities)
            arm_reported = reported.get("strategies", {}).get(arm, {})
            for key in DISCRIMINATION_KEYS:
                ledger.close(f"folds/{fold}/strategies/{arm}/{key}", observed.get(key), arm_reported.get(key), 0.0)
            recomputed = r02._bootstrap_discrimination(
                dates=sessions,
                row_start=starts,
                row_count=counts,
                labels=labels,
                probs=np.asarray(probabilities, dtype=np.float64),
                seed=r02.BOOTSTRAP_SEED,
            )
            recorded = intervals.get(arm, {}).get("discrimination", {})
            for metric in ("brier_score", "roc_auc"):
                for bound in ("lower", "upper"):
                    ledger.close(
                        f"intervals/{fold}/{arm}/discrimination/{metric}/{bound}",
                        recomputed[metric][bound],
                        recorded.get(metric, {}).get(bound),
                    )

        primary = np.asarray(frame["probability_primary_model"].to_numpy(), dtype=np.float64)
        expected_decision = (primary >= r02.DECISION_THRESHOLD).astype(np.int8)
        ledger.expect(
            f"folds/{fold}/decision_primary_model is the frozen threshold on the primary probability",
            bool(np.array_equal(expected_decision, frame["decision_primary_model"].to_numpy())),
        )

    train_base_rate = metrics.get("inputs", {}).get("train_base_rate")
    if predictions.height:
        no_skill = set(predictions["probability_no_skill"].unique().to_list())
        ledger.expect(
            "the no-skill probability is the single train base rate metrics.json reports",
            len(no_skill) == 1 and math.isclose(float(next(iter(no_skill))), float(train_base_rate or 0.0), abs_tol=TOLERANCE),
            f"predictions {sorted(no_skill)} vs inputs.train_base_rate {train_base_rate}",
        )


def _check_comparison(baselines: Mapping[str, Any], metrics: Mapping[str, Any], ledger: _Ledger) -> None:
    for fold in FOLD_NAMES:
        recorded = baselines.get("comparison", {}).get(fold, {})
        strategies = metrics.get("folds", {}).get(fold, {}).get("strategies", {})
        if not recorded or not strategies:
            continue
        net = {arm: strategies.get(arm, {}).get("economics", {}).get("net_return") for arm in ARM_NAMES}
        sharpe = {arm: strategies.get(arm, {}).get("economics", {}).get("sharpe_ratio") for arm in ARM_NAMES}
        brier = {arm: strategies.get(arm, {}).get("brier_score") for arm in ARM_NAMES}
        if None in net.values() or None in sharpe.values() or None in brier.values():
            continue
        deltas = {
            "primary_minus_technical_net_return": net["primary_model"] - net["technical_rule"],
            "primary_minus_simple_model_net_return": net["primary_model"] - net["simple_model"],
            "primary_minus_technical_sharpe_ratio": sharpe["primary_model"] - sharpe["technical_rule"],
            "brier_primary_minus_technical": brier["primary_model"] - brier["technical_rule"],
            "brier_primary_minus_no_skill": brier["primary_model"] - brier["no_skill"],
        }
        for key, observed in deltas.items():
            ledger.close(f"baselines/{fold}/{key}", observed, recorded.get(key), TOLERANCE if "net_return" in key or "sharpe" in key else 0.0)
        ledger.expect(f"baselines/{fold}/strategies mirrors metrics.json", recorded.get("strategies") == strategies)
        matched = baselines.get("matched_dates", {}).get(fold, {})
        fold_metrics = metrics.get("folds", {}).get(fold, {})
        ledger.expect(f"baselines/{fold}/matched_dates rows", matched.get("rows") == fold_metrics.get("rows"))
        ledger.expect(f"baselines/{fold}/matched_dates sessions", matched.get("sessions") == fold_metrics.get("sessions"))
        ledger.expect(
            f"baselines/{fold}/matched_dates rebalance_blocks",
            matched.get("rebalance_blocks") == math.ceil((fold_metrics.get("sessions") or 0) / r02.HOLDING_SESSIONS),
        )


def _check_promotion(metrics: Mapping[str, Any], ledger: _Ledger) -> None:
    folds = {fold: metrics.get("folds", {}).get(fold, {}) for fold in FOLD_NAMES}
    intervals = metrics.get("intervals", {})
    recorded = metrics.get("promotion", {})
    if not folds["test"] or not intervals:
        return
    recomputed = r02._promotion_verdict(spec=r02.r02_spec(), folds=folds, intervals=intervals)
    ledger.expect("the promotion verdict reproduces from the archived numbers", recomputed == recorded)
    ledger.expect("nothing is promoted", recorded.get("promoted") is False and recorded.get("would_promote_if_authorized") is False)
    ledger.expect("exactly the risk criterion is met", recorded.get("criteria_met") == ["risk"], f"criteria_met {recorded.get('criteria_met')}")


def _reconcile_report(metrics: Mapping[str, Any], baselines: Mapping[str, Any], report: str, ledger: _Ledger) -> None:
    folds = metrics.get("folds", {})
    for fold in FOLD_NAMES:
        for arm in ARM_NAMES:
            entry = folds.get(fold, {}).get("strategies", {}).get(arm, {})
            economics = entry.get("economics", {})
            row = (
                f"| {ARM_LABELS[arm]} | {r02._fmt(entry.get('brier_score'))} | {r02._fmt(entry.get('roc_auc'))} "
                f"| {r02._fmt(economics.get('net_return'))} | {r02._fmt(economics.get('sharpe_ratio'))} | {r02._fmt(economics.get('max_drawdown'))} |"
            )
            ledger.expect(f"report.md renders the {fold}/{arm} row from metrics.json", row in report, row)
    paired = metrics.get("intervals", {}).get("test", {}).get("paired_difference_net_return_primary_minus_technical", {})
    compounded = baselines.get("comparison", {}).get("test", {}).get("primary_minus_technical_net_return")
    bounds = f"[{r02._fmt(paired.get('lower'))}, {r02._fmt(paired.get('upper'))}]"
    row = f"| net return difference (primary - technical) | {r02._fmt(compounded)} | {bounds} |"
    ledger.expect("report.md pairs the compounded difference with the paired-difference interval", row in report, row)
    ledger.finding(
        "report.md (and metrics.json's economics detail) puts the compounded net-return difference "
        f"{r02._fmt(compounded)} next to the interval [{r02._fmt(paired.get('lower'))}, {r02._fmt(paired.get('upper'))}] "
        "that belongs to the mean per-session difference"
    )


def _gold_closes(lake_dir: Path) -> tuple[dict[tuple[str, str, str], dict[date, float]], list[date]]:
    """Re-read the frozen pre-holdout Gold read and index closes per instrument/session."""
    spec = r02.r02_spec()
    features = r02._load_features(
        lake_dir=Path(lake_dir),
        instruments=r02._instruments(spec.universe),
        start_date=date(2024, 1, 2),
        end_date=spec.test_end,
    )
    assigned, _ = r02._assign_folds(r02._label_rows(features, spec.label_horizon_sessions), spec)
    identity = ["market", "mic", "symbol"]
    closes: dict[tuple[str, str, str], dict[date, float]] = {}
    for row in assigned.select(*identity, "date", "close").to_dicts():
        closes.setdefault((row["market"], row["mic"], row["symbol"]), {})[row["date"]] = float(row["close"])
    return closes, sorted(set(assigned["date"].to_list()))


def _recompute_economics(
    predictions: pl.DataFrame,
    metrics: Mapping[str, Any],
    lake_dir: Path,
    ledger: _Ledger,
) -> None:
    try:
        closes, sessions = _gold_closes(lake_dir)
    except Exception as exc:  # a lake without the frozen weak-basis rows cannot recover the closes
        ledger.unverified_reason(f"economic metrics: the Gold read at {lake_dir} failed ({exc.__class__.__name__}: {exc})")
        return

    recorded_intervals = metrics.get("intervals", {})
    fold_returns: dict[str, dict[str, pl.DataFrame]] = {}
    for fold in FOLD_NAMES:
        frame = _fold_frame(predictions, fold)
        fold_sessions = sorted(set(frame["date"].to_list()))
        fold_returns[fold] = {}
        for arm in ARM_NAMES:
            picks: dict[date, list[tuple[str, str, str]]] = {}
            for session in fold_sessions:
                day = frame.filter(pl.col("date") == session)
                probabilities = np.asarray(day[f"probability_{arm}"].to_numpy(), dtype=np.float64)
                picks[session] = [
                    (str(row["market"]), str(row["mic"]), str(row["symbol"]))
                    for row, probability in zip(day.select("market", "mic", "symbol").to_dicts(), probabilities, strict=True)
                    if probability >= r02.DECISION_THRESHOLD
                ]
            returns = r02._strategy_returns(
                picks=picks,
                sessions=sessions,
                closes=closes,
                cost=r02.ROUND_TRIP_COST,
                holding=r02.HOLDING_SESSIONS,
            ).filter(pl.col("date").is_in(fold_sessions))
            fold_returns[fold][arm] = returns
            observed = r02._economic_summary(returns)
            reported = metrics.get("folds", {}).get(fold, {}).get("strategies", {}).get(arm, {}).get("economics", {})
            for key in ECONOMIC_KEYS:
                ledger.close(f"folds/{fold}/strategies/{arm}/economics/{key}", observed.get(key), reported.get(key))
            bootstrapped = r02._bootstrap_economics(returns, r02.BOOTSTRAP_SEED)
            recorded = recorded_intervals.get(fold, {}).get(arm, {})
            for metric in ("net_return", "sharpe_ratio", "max_drawdown"):
                for bound in ("lower", "upper"):
                    ledger.close(f"intervals/{fold}/{arm}/{metric}/{bound}", bootstrapped[metric][bound], recorded.get(metric, {}).get(bound))

    for fold in FOLD_NAMES:
        paired = r02._bootstrap_paired_difference(fold_returns[fold]["primary_model"], fold_returns[fold]["technical_rule"], r02.BOOTSTRAP_SEED)
        recorded = recorded_intervals.get(fold, {}).get("paired_difference_net_return_primary_minus_technical", {})
        for bound in ("lower", "upper"):
            ledger.close(f"intervals/{fold}/paired_difference_net_return_primary_minus_technical/{bound}", paired[bound], recorded.get(bound))

    primary = metrics.get("folds", {}).get("test", {}).get("strategies", {}).get("primary_model", {}).get("economics", {})
    technical = metrics.get("folds", {}).get("test", {}).get("strategies", {}).get("technical_rule", {}).get("economics", {})
    paired = recorded_intervals.get("test", {}).get("paired_difference_net_return_primary_minus_technical", {})
    if not primary or not technical or not paired:
        return
    compounded = primary["net_return"] - technical["net_return"]
    per_session = primary["mean_daily_return"] - technical["mean_daily_return"]
    lower, upper = paired["lower"], paired["upper"]
    ledger.expect(
        "the recorded paired interval brackets the mean per-session difference it resamples",
        lower <= per_session <= upper,
        f"{per_session} outside [{lower}, {upper}]",
    )
    ledger.finding(
        f"paired-difference estimands (test fold): compounded net-return difference {compounded:.10f} "
        f"({compounded * 100:.2f} pp) vs mean per-session net-return difference {per_session:.10f} ({per_session * 100:.4f} pp); "
        f"the recorded 95% interval [{lower:.10f}, {upper:.10f}] = [{lower * 100:.4f} pp, {upper * 100:.4f} pp] brackets the per-session "
        f"value ({'inside' if lower <= per_session <= upper else 'outside'}) and the compounded value "
        f"({'inside' if lower <= compounded <= upper else 'outside'})"
    )


def verify(research_dir: Path, anchor_path: Path, lake_dir: Path | None = None) -> Outcome:
    """Verify one archived R02 directory against the tracked anchor.

    Args:
        research_dir: the archive (normally ``data/research/r02``); its sibling
            ``protocols/`` directory is where the R00 manifest is looked for.
        anchor_path: the tracked receipt carrying the digest table.
        lake_dir: optional Gold root; when present the economic metrics and their
            intervals are recomputed from per-session closes, when absent they are
            reported as unverified with that reason.

    Raises:
        ArtifactsAbsent: the archive directory does not exist.
        VerificationError: the anchor is missing or unusable.
    """
    research_dir = Path(research_dir)
    if not research_dir.is_dir():
        raise ArtifactsAbsent(f"{research_dir} is absent; there is no archived R02 artifact to verify (nothing is regenerated by refitting)")
    anchor = load_anchor(Path(anchor_path))
    ledger = _Ledger()
    ledger.outcome.research_dir = research_dir

    _check_digests(research_dir, anchor, ledger)
    payloads = _load_json_artifacts(research_dir, ledger)
    predictions = _load_predictions(research_dir, ledger)
    metrics: Mapping[str, Any] = payloads.get("metrics.json", {})
    baselines: Mapping[str, Any] = payloads.get("baselines.json", {})
    _check_binding(research_dir, anchor, payloads, predictions, ledger)
    if predictions is None:
        ledger.unverified_reason("every metric: predictions.parquet is unreadable, so nothing can be recomputed")
    else:
        _recompute_discrimination(predictions, metrics, ledger)
        _check_comparison(baselines, metrics, ledger)
        _check_promotion(metrics, ledger)
        report = (research_dir / "report.md").read_text(encoding="utf-8") if (research_dir / "report.md").is_file() else ""
        if report:
            _reconcile_report(metrics, baselines, report, ledger)
        else:
            ledger.unverified_reason("report.md: absent, so nothing was reconciled against the rendered report")
        if lake_dir is not None:
            _recompute_economics(predictions, metrics, Path(lake_dir), ledger)
        else:
            ledger.unverified_reason(
                "economic metrics (net return, Sharpe, max drawdown, mean daily return, their intervals and the paired-difference interval): "
                "no --lake-dir given; they need the per-session closes in the Gold tables, which predictions.parquet does not carry"
            )
    _check_run_counts(payloads.get("run.json", {}), predictions, ledger)
    return ledger.outcome


def _check_run_counts(run: Mapping[str, Any], predictions: pl.DataFrame | None, ledger: _Ledger) -> None:
    counts = run.get("row_counts", {})
    if not counts:
        ledger.unverified_reason("run.json: absent or carrying no row counts, so the recorded counts were not cross-checked")
        return
    if predictions is not None:
        ledger.expect("run.json prediction_rows equals the archived prediction rows", counts.get("prediction_rows") == predictions.height)
        for fold in FOLD_NAMES:
            ledger.expect(
                f"run.json {fold}_rows equals the archived {fold} rows",
                counts.get(f"{fold}_rows") == predictions.filter(pl.col("fold") == fold).height,
            )
    model = run.get("model", {})
    ledger.expect(
        "run.json records exactly one fit and no refit or sweep", model.get("fits") == 1 and model.get("refits") == 0 and model.get("sweeps") == 0
    )
    ledger.expect("run.json records the holdout as unread", run.get("holdout_untouched", {}).get("read") is False)


def _print_outcome(outcome: Outcome) -> None:
    print(f"R02 archive: {outcome.research_dir}")
    for name in sorted(outcome.digests):
        print(f"  sha256 {outcome.digests[name]}  {name}")
    print(f"checks: {outcome.checked}, mismatches: {len(outcome.mismatches)}")
    for finding in outcome.findings:
        print(f"FINDING: {finding}")
    for reason in outcome.unverified:
        print(f"UNVERIFIED: {reason}")
    for mismatch in outcome.mismatches:
        print(f"MISMATCH: {mismatch}")


def main(argv: Sequence[str] | None = None) -> int:
    """CLI entrypoint: 0 verified, 1 mismatch/tamper, 2 nothing to verify."""
    parser = argparse.ArgumentParser(description="Verify the archived R02 research artifacts offline (never writes)")
    parser.add_argument(
        "--research-dir",
        default=str(r02.results_root()),
        help="archive directory to verify (default: data/research/r02)",
    )
    parser.add_argument(
        "--anchor",
        default=str(DEFAULT_ANCHOR),
        help="tracked receipt carrying the digest table",
    )
    parser.add_argument(
        "--lake-dir",
        default=None,
        help="Gold root used to recompute the economic metrics from per-session closes (optional)",
    )
    args = parser.parse_args(argv)
    try:
        outcome = verify(Path(args.research_dir), Path(args.anchor), None if args.lake_dir is None else Path(args.lake_dir))
    except ArtifactsAbsent as exc:
        print(f"SKIPPED: {exc}", file=sys.stderr)
        return 2
    except VerificationError as exc:
        print(f"REFUSED: {exc}", file=sys.stderr)
        return 1
    _print_outcome(outcome)
    return 0 if outcome.verified else 1


if __name__ == "__main__":
    sys.exit(main())


