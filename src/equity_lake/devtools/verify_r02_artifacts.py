"""Verify the archived R02 research artifacts offline (residual stage RS-R02-D1).

Module CLI entrypoint (``python -m``, invoked by the operator and by the unit tests):
uses plain ``print``/``stderr`` output instead of structlog by devtool convention.

The archive under ``data/research/r02/`` is evidence, not source: it lives in a
gitignored root, so the tracked anchor for it is the digest table in
``docs/finding/<date>-01-r02-recovery-receipt.md``. This module reads that anchor and
the archive, and never writes anywhere — it opens files for reading only, so an
in-place verification cannot mutate the evidence it verifies.

What it establishes, in order:

* **Integrity** — the sha256 of each archived file matches the tracked anchor, and the
  archive holds exactly the recorded files.
* **Binding** — the two digests are re-derived from the frozen code
  (:func:`~equity_lake.ml.experiment.r02_protocol` /
  :func:`~equity_lake.ml.experiment.r02_spec`) without freezing or writing anything,
  every artifact carries them, the archived prespecification and protocol payloads are
  the frozen ones, and the R00 manifest next to the archive binds
  ``input_digests.r02_prespecification``.
* **Recomputation** — every metric the immutable artifacts support is recomputed with
  :mod:`equity_lake.ml.experiment`'s own estimators: discrimination scores and their
  block-bootstrap intervals from ``predictions.parquet`` alone, and the economic
  metrics plus their intervals from ``predictions.parquet`` and the per-session closes
  in the Gold tables (``--lake-dir``). No model is fitted, so this is not a refit.
* **Estimand** — the reported ``-2.79 pp`` is the difference of *compounded* net
  returns while the reported interval belongs to the *mean per-session* difference
  (``_bootstrap_paired_difference``). Both quantities and both readings are reproduced
  and reported; the pairing is recorded as a finding, never silently accepted.

Exit codes: ``0`` verified, ``1`` mismatch or tamper, ``2`` no archive to verify.
"""

